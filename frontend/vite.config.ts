/// <reference types="vitest/config" />
import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'
import { VitePWA } from 'vite-plugin-pwa'

const brown = '#8a4b16'

// https://vite.dev/config/
export default defineConfig({
  plugins: [
    react(),
    // Installable app ("Lägg till på hemskärmen") with a service worker that keeps the app shell
    // and the latest API answers on the device. See README, "Installera som app".
    VitePWA({
      // A new version waits until the user chooses "Ladda om" (see PwaUpdatePrompt).
      registerType: 'prompt',
      // Icons index.html links (generated by pwa-assets.config.ts); the manifest's are added too.
      includeAssets: ['favicon.ico', 'apple-touch-icon-180x180.png', 'pwa-icon.svg'],
      manifest: {
        name: 'Pourfolio',
        short_name: 'Pourfolio',
        description: 'Inventarie för drycker hemma och förslag på drinkar.',
        lang: 'sv',
        start_url: '/',
        scope: '/',
        display: 'standalone',
        theme_color: brown,
        background_color: '#ffffff',
        icons: [
          { src: 'pwa-64x64.png', sizes: '64x64', type: 'image/png' },
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png' },
          {
            src: 'maskable-icon-512x512.png',
            sizes: '512x512',
            type: 'image/png',
            purpose: 'maskable',
          },
        ],
      },
      workbox: {
        // The app shell. The scanner's .wasm (~1 MB) is cached when first used instead.
        globPatterns: ['**/*.{js,css,html}'],
        // Deep links like /items/12 open offline too, but never answer API calls with the app.
        navigateFallback: '/index.html',
        navigateFallbackDenylist: [/^\/api\//],
        cleanupOutdatedCaches: true,
        runtimeCaching: [
          {
            // Data: always ask the server first, fall back to the last answer when offline.
            // The API may be on another host (VITE_API_URL), so match on the path. Sign-in is
            // never cached. The cache is emptied when signing out (src/pwa/apiCache.ts).
            urlPattern: ({ url, request }) =>
              request.method === 'GET' &&
              url.pathname.startsWith('/api/') &&
              !url.pathname.startsWith('/api/auth/'),
            handler: 'NetworkFirst',
            options: {
              cacheName: 'api',
              // Render's free tier can take a minute to wake up; don't wait for it when offline.
              networkTimeoutSeconds: 10,
              cacheableResponse: { statuses: [200] },
              expiration: { maxEntries: 200, maxAgeSeconds: 7 * 24 * 60 * 60 },
            },
          },
          {
            urlPattern: ({ url }) => url.pathname.endsWith('.wasm'),
            handler: 'CacheFirst',
            options: {
              cacheName: 'wasm',
              cacheableResponse: { statuses: [200] },
              expiration: { maxEntries: 2 },
            },
          },
        ],
      },
    }),
  ],
  server: {
    // In development, /api calls go to the local Spring Boot backend.
    proxy: {
      '/api': {
        target: 'http://localhost:8080',
        // Proxied calls are same-origin from the browser's point of view; drop Origin so the
        // backend's CORS check (meant for separately hosted frontends) doesn't apply.
        configure: (proxy) => proxy.on('proxyReq', (proxyReq) => proxyReq.removeHeader('origin')),
      },
    },
  },
  test: {
    environment: 'jsdom',
    // Playwright specs in e2e/ run separately via npm run e2e.
    include: ['src/**/*.test.{ts,tsx}'],
    setupFiles: ['./src/test/setup.ts'],
    // Whole-app UI tests type into forms; leave room for slow, busy CI machines.
    testTimeout: 15_000,
  },
})
