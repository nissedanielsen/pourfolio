-- Drink recipes and their ingredient lines. A line asks either for a specific ingredient
-- ("Campari") or for any item in a category ("any gin").

CREATE TABLE recipe (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50)  NOT NULL UNIQUE,
    name        VARCHAR(100) COLLATE swedish NOT NULL,
    description VARCHAR(500),
    method      TEXT         NOT NULL,
    glass       VARCHAR(100),
    garnish     VARCHAR(200)
);

-- Units: ML (amount in ml), DASH (a few drops), TSP (teaspoon, ~5 ml),
-- PIECE (whole pieces, e.g. a lime or an egg), TOP_UP (fill up the glass; no amount).
CREATE TABLE recipe_ingredient (
    id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    recipe_id     BIGINT       NOT NULL REFERENCES recipe (id) ON DELETE CASCADE,
    position      INT          NOT NULL,
    amount        NUMERIC(6, 1) CHECK (amount > 0),
    unit          VARCHAR(16)  NOT NULL CHECK (unit IN ('ML', 'DASH', 'TSP', 'PIECE', 'TOP_UP')),
    ingredient_id BIGINT       REFERENCES ingredient (id),
    category_id   BIGINT       REFERENCES category (id),
    optional      BOOLEAN      NOT NULL DEFAULT FALSE,
    UNIQUE (recipe_id, position),
    -- Exactly one of a specific ingredient or a category.
    CONSTRAINT chk_ingredient_or_category CHECK ((ingredient_id IS NULL) <> (category_id IS NULL)),
    CONSTRAINT chk_amount_for_unit CHECK ((unit = 'TOP_UP') = (amount IS NULL))
);

CREATE INDEX idx_recipe_ingredient_recipe ON recipe_ingredient (recipe_id);

